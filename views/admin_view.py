    def setup_kpi_cards(self):
        kpi_row = ctk.CTkFrame(self, fg_color="transparent")
        kpi_row.pack(fill="x", padx=25, pady=(15, 10))
        
        total_polls = len(self.polls)
        total_students = len(get_all_students())
        
        # Calculate active turnout
        active_turnout = 0
        if self.polls:
            data = get_admin_detailed_data(self.polls[0]['id'])
            active_turnout = data['turnout_pct'] if data else 0
            
        self.create_metric_card(kpi_row, "Total QR Polls", f"{total_polls}", "Generated by cook", "📱", COLOR_PRIMARY)
        self.create_metric_card(kpi_row, "Hostel Students", f"{total_students}", "Registered in hostel", "🎓", COLOR_PRIMARY_DARK)
        self.create_metric_card(kpi_row, "Current Turnout", f"{active_turnout}%", "Student participation", "📊", COLOR_SUCCESS)
        self.create_metric_card(kpi_row, "Today's Status", "Online", datetime.now().strftime("%d %b %Y"), "⚡", COLOR_SPECIAL)
        
