    def setup_charts_tab(self):
        container = ctk.CTkFrame(self.tab_charts, fg_color="transparent")
        container.pack(fill="both", expand=True, padx=10, pady=10)
        
        # Render charts for current poll
        data = get_admin_detailed_data(self.selected_poll_id) if self.selected_poll_id else None
        if not data or not data['dish_results']:
            ctk.CTkLabel(container, text="No voting data available for charts.").pack(pady=40)
            return
            
        fig = Figure(figsize=(9, 4.5), dpi=100, facecolor=COLOR_BG_CARD)
        
        # 1. Donut chart: Polled vs Didn't Poll
        ax1 = fig.add_subplot(121)
        ax1.set_facecolor(COLOR_BG_CARD)
        labels = ['Polled', "Didn't Poll"]
        sizes = [data['polled_count'], data['non_polled_count']]
        colors = ['#38BDF8', '#E2E8F0']
        
        wedges, texts, autotexts = ax1.pie(
            sizes, 
            labels=labels, 
            autopct='%1.1f%%', 
            startangle=90, 
            colors=colors,
            textprops={'fontsize': 10, 'color': '#0F172A'},
            wedgeprops=dict(width=0.4, edgecolor='white')
        )
        for autotext in autotexts:
            autotext.set_color('#0F172A')
            autotext.set_weight('bold')
        ax1.set_title("Turnout Participation Rate", fontsize=12, fontweight='bold', color='#0284C7', pad=10)
        
        # 2. Horizontal Bar chart: Votes per dish
        ax2 = fig.add_subplot(122)
        ax2.set_facecolor(COLOR_BG_CARD)
        dish_names = [d['name'][:18] + '...' if len(d['name']) > 18 else d['name'] for d in data['dish_results']][::-1]
        dish_votes = [d['vote_count'] for d in data['dish_results']][::-1]
        
        bars = ax2.barh(dish_names, dish_votes, color='#0284C7', height=0.55, edgecolor='#38BDF8')
        ax2.set_xlabel('Number of Votes', fontsize=10, color='#64748B')
        ax2.set_title("Dish Voting Preference", fontsize=12, fontweight='bold', color='#0284C7', pad=10)
        ax2.spines['top'].set_visible(False)
        ax2.spines['right'].set_visible(False)
        ax2.spines['left'].set_color('#CBD5E1')
        ax2.spines['bottom'].set_color('#CBD5E1')
        ax2.tick_params(colors='#334155', labelsize=9)
        
        for bar in bars:
            width = bar.get_width()
            ax2.text(width + 0.2, bar.get_y() + bar.get_height()/2, f"{int(width)}", 
                     ha='left', va='center', fontsize=9, fontweight='bold', color='#0284C7')
                     
        fig.tight_layout(pad=2.5)
        
        chart_canvas = FigureCanvasTkAgg(fig, master=container)
        chart_canvas.draw()
        chart_canvas.get_tk_widget().pack(fill="both", expand=True)

