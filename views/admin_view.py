    def on_turnout_poll_changed(self, val):
        if val and " - " in val:
            self.selected_poll_id = val.split(" - ")[0].strip()
            self.render_turnout_data()
            
    def render_turnout_data(self):
        if not self.selected_poll_id:
            return
            
        data = get_admin_detailed_data(self.selected_poll_id)
        self.current_poll_data = data
        if not data:
            return
            
        poll = data['poll']
        self.kpi_banner_lbl.configure(
            text=f"📊 Session: {poll['title']}  •  Total Students: {data['total_hostel_students']}  •  "
                 f"Polled: {data['polled_count']} ({data['turnout_pct']}%)  •  "
                 f"Didn't Poll: {data['non_polled_count']}  •  "
                 f"Leading Choice: 👑 {data['winner']}"
        )
        
        self.polled_head_lbl.configure(text=f"✅ Students Who Polled ({data['polled_count']}) & Their Choices")
        self.non_polled_head_lbl.configure(text=f"❌ Students Who Didn't Poll ({data['non_polled_count']})")
        
        self.filter_turnout_tables()
        
    def filter_turnout_tables(self):
        if not self.current_poll_data:
            return
            
        search_query = self.search_entry.get().strip().lower()
        
        # 1. Populate Polled Students
        for w in self.polled_scroll.winfo_children():
            w.destroy()
            
        polled = self.current_poll_data['polled_students']
        filtered_polled = [
            s for s in polled
            if not search_query or (search_query in s['name'].lower() or search_query in s['student_id'].lower() or search_query in s['room_no'].lower() or search_query in s['chosen_dish'].lower())
        ]
        
        if not filtered_polled:
            ctk.CTkLabel(self.polled_scroll, text="No polled students found.", font=FONT_CAPTION, text_color=COLOR_TEXT_MUTED).pack(pady=15)
        else:
            for s in filtered_polled:
                row = ctk.CTkFrame(self.polled_scroll, fg_color=COLOR_BG_CARD_ALT, border_width=1, border_color=COLOR_BORDER_LIGHT, corner_radius=8)
                row.pack(fill="x", pady=3)
                
                r_top = ctk.CTkFrame(row, fg_color="transparent")
                r_top.pack(fill="x", padx=10, pady=(6, 2))
                
                ctk.CTkLabel(r_top, text=f"{s['name']} ({s['student_id']})", font=FONT_BODY_BOLD, text_color=COLOR_TEXT_MAIN).pack(side="left")
                ctk.CTkLabel(r_top, text=f"Room: {s['room_no']} • {s['block']}", font=FONT_CAPTION_BOLD, text_color=COLOR_PRIMARY_DARK).pack(side="right")
                
                r_bottom = ctk.CTkFrame(row, fg_color="transparent")
                r_bottom.pack(fill="x", padx=10, pady=(0, 6))
                
                dish_pill = ctk.CTkFrame(r_bottom, fg_color=COLOR_LIGHT_ACCENT, corner_radius=6)
                dish_pill.pack(side="left")
                ctk.CTkLabel(dish_pill, text=f"Voted: {s['chosen_dish']}", font=FONT_CAPTION_BOLD, text_color=COLOR_DEEP_OCEAN).pack(padx=6, pady=1)
                
                v_time = s['voted_at'].split(" ")[-1] if " " in s['voted_at'] else s['voted_at']
                ctk.CTkLabel(r_bottom, text=f"at {v_time}", font=FONT_CAPTION, text_color=COLOR_TEXT_LIGHT).pack(side="right")
                
        # 2. Populate Non-Polled Students
        for w in self.non_polled_scroll.winfo_children():
            w.destroy()
            
        non_polled = self.current_poll_data['non_polled_students']
        filtered_np = [
            s for s in non_polled
            if not search_query or (search_query in s['name'].lower() or search_query in s['student_id'].lower() or search_query in s['room_no'].lower() or search_query in s.get('department', '').lower())
        ]
        
        if not filtered_np:
            ctk.CTkLabel(self.non_polled_scroll, text="No students match criteria.", font=FONT_CAPTION, text_color=COLOR_TEXT_MUTED).pack(pady=15)
        else:
            for s in filtered_np:
                row = ctk.CTkFrame(self.non_polled_scroll, fg_color=COLOR_BG_CARD_ALT, border_width=1, border_color=COLOR_BORDER_LIGHT, corner_radius=8)
                row.pack(fill="x", pady=3)
                
                r_top = ctk.CTkFrame(row, fg_color="transparent")
                r_top.pack(fill="x", padx=10, pady=(6, 2))
                
                ctk.CTkLabel(r_top, text=f"{s['name']} ({s['student_id']})", font=FONT_BODY_BOLD, text_color=COLOR_TEXT_MAIN).pack(side="left")
                ctk.CTkLabel(r_top, text=f"Room: {s['room_no']} • {s['block']}", font=FONT_CAPTION_BOLD, text_color=COLOR_DANGER).pack(side="right")
                
                r_bottom = ctk.CTkFrame(row, fg_color="transparent")
                r_bottom.pack(fill="x", padx=10, pady=(0, 6))
                
                ctk.CTkLabel(r_bottom, text=f"Dept: {s.get('department', 'General')}", font=FONT_CAPTION, text_color=COLOR_TEXT_MUTED).pack(side="left")
                if s.get('phone'):
                    ctk.CTkLabel(r_bottom, text=f"📞 {s['phone']}", font=FONT_CAPTION, text_color=COLOR_TEXT_LIGHT).pack(side="right")

