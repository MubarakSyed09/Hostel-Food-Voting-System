        for p in polls:
            card = ctk.CTkFrame(self.qr_scroll, fg_color=COLOR_BG_CARD_ALT, border_width=1, border_color=COLOR_BORDER_LIGHT, corner_radius=10)
            card.pack(fill="x", pady=5)
            
