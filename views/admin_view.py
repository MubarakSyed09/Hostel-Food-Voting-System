    def export_csv_report(self):
        if not self.selected_poll_id:
            messagebox.showwarning("Export", "No poll selected to export.")
            return
            
        data = get_admin_detailed_data(self.selected_poll_id)
        if not data:
            return
            
        target = filedialog.asksaveasfilename(
            defaultextension=".csv",
            filetypes=[("CSV file", "*.csv")],
            initialfile=f"Hostel_Poll_{self.selected_poll_id}_Report.csv"
        )
        if target:
            with open(target, mode="w", newline="", encoding="utf-8") as f:
                writer = csv.writer(f)
                writer.writerow(["HOSTEL MESS SMART VOTING AUDIT REPORT"])
                writer.writerow(["Poll ID", data['poll']['id']])
                writer.writerow(["Title", data['poll']['title']])
                writer.writerow(["Date", data['poll']['date']])
                writer.writerow(["Meal Type", data['poll']['meal_type']])
                writer.writerow(["Generated By", data['poll']['created_by']])
                writer.writerow(["Expiry Time", data['poll']['expires_at']])
                writer.writerow([])
                writer.writerow(["TURNOUT SUMMARY"])
                writer.writerow(["Total Registered Students", data['total_hostel_students']])
                writer.writerow(["Polled Students", data['polled_count']])
                writer.writerow(["Didn't Poll Students", data['non_polled_count']])
                writer.writerow(["Turnout Percentage", f"{data['turnout_pct']}%"])
                writer.writerow([])
                writer.writerow(["DISH RESULTS"])
                writer.writerow(["Dish Name", "Category", "Votes", "Percentage"])
                for d in data['dish_results']:
                    writer.writerow([d['name'], d['category'], d['vote_count'], f"{d['percentage']}%"])
                writer.writerow([])
                writer.writerow(["STUDENTS WHO POLLED"])
                writer.writerow(["Student ID", "Name", "Room No", "Block", "Chosen Dish", "Vote Timestamp"])
                for s in data['polled_students']:
                    writer.writerow([s['student_id'], s['name'], s['room_no'], s['block'], s['chosen_dish'], s['voted_at']])
                writer.writerow([])
                writer.writerow(["STUDENTS WHO DID NOT POLL"])
                writer.writerow(["Student ID", "Name", "Room No", "Block", "Department", "Phone"])
                for s in data['non_polled_students']:
                    writer.writerow([s['student_id'], s['name'], s['room_no'], s['block'], s['department'], s.get('phone', '')])
                    
            messagebox.showinfo("Export Successful", f"Full admin report exported to:\n{target}")
