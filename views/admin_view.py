            badge.pack(side="left")
            ctk.CTkLabel(badge, text=p['status'], font=FONT_CAPTION_BOLD, text_color=COLOR_SUCCESS if is_active else COLOR_DANGER).pack(padx=6, pady=1)
            
            ctk.CTkLabel(top_row, text=p['date'], font=FONT_CAPTION_BOLD, text_color=COLOR_TEXT_MUTED).pack(side="right")
            
            ctk.CTkLabel(card, text=p['title'], font=FONT_BODY_BOLD, text_color=COLOR_TEXT_MAIN, anchor="w").pack(fill="x", padx=10, pady=2)
